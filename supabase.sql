create table if not exists public.plantas (
 id bigint generated by default as identity primary key,
 codigo text not null unique,
 nombre text not null,
 categoria text not null check (categoria in ('Interior','Exterior','Suculentas y cactus','Ornamentales','Frutales','Aromáticas y medicinales','Otras')),
 precio numeric(10,2) not null check (precio >= 0),
 stock integer not null default 0 check (stock >= 0),
 descripcion text not null default '',
 fotos text[] not null default '{}',
 creado_en timestamptz not null default now()
);
create table if not exists public.configuracion (id integer primary key check (id=1),whatsapp text not null default '');
insert into public.configuracion(id,whatsapp) values (1,'') on conflict(id) do nothing;
-- Solo el usuario administrador autorizado puede escribir.
-- Reemplaza el correo de abajo por el correo real del administrador antes de ejecutar.
create or replace function public.es_admin_vivero() returns boolean language sql stable security definer set search_path = '' as $$
 select exists(select 1 from auth.users where id = (select auth.uid()) and lower(email) = lower('ADMIN@EJEMPLO.COM'));
$$;
revoke all on function public.es_admin_vivero() from public;
grant execute on function public.es_admin_vivero() to authenticated;
alter table public.plantas enable row level security;
alter table public.configuracion enable row level security;
create policy "lectura publica plantas" on public.plantas for select to anon, authenticated using (true);
create policy "admin inserta plantas" on public.plantas for insert to authenticated with check (public.es_admin_vivero());
create policy "admin actualiza plantas" on public.plantas for update to authenticated using (public.es_admin_vivero()) with check (public.es_admin_vivero());
create policy "admin elimina plantas" on public.plantas for delete to authenticated using (public.es_admin_vivero());
create policy "lectura publica contacto" on public.configuracion for select to anon, authenticated using (true);
create policy "admin actualiza contacto" on public.configuracion for update to authenticated using (public.es_admin_vivero()) with check (public.es_admin_vivero());
insert into storage.buckets (id,name,public,file_size_limit,allowed_mime_types) values ('plantas','plantas',true,5242880,array['image/jpeg','image/png','image/webp','image/gif']) on conflict(id) do nothing;
create policy "imagenes publicas vivero" on storage.objects for select to anon,authenticated using (bucket_id='plantas');
create policy "admin sube imagenes vivero" on storage.objects for insert to authenticated with check (bucket_id='plantas' and public.es_admin_vivero());
create policy "admin elimina imagenes vivero" on storage.objects for delete to authenticated using (bucket_id='plantas' and public.es_admin_vivero());
